/*
 * Summarises the source-processing artifacts in docs/pmp-curriculum into
 * server/pmp/sourceStats.ts, so the admin panel can show real processing figures without
 * bundling the full page manifest into the server.
 *
 * Run: node scripts/pmp-build-source-stats.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const DOCS = new URL('../docs/pmp-curriculum/', import.meta.url);
const read = (f: string) => JSON.parse(readFileSync(new URL(f, DOCS), 'utf8'));

interface PageRecord {
  pdfPage: number;
  printedPage?: string;
  book: string;
  pageType: string;
  extractionStatus?: string;
  visualInspection?: string;
  analysisStatus?: string;
  curriculumMapping?: string;
  verificationStatus?: string;
  topics?: string[];
  issues?: string[];
  disposition?: string;
  batch?: string;
}

const manifest = read('page-processing-manifest.json');
const pages: PageRecord[] = manifest.pages;
const sourceIndex = read('source-index.json');
const checkpoint = read('checkpoint.json');
const catalogueRaw = read('topic-catalogue.json');
const catalogue: Record<string, { title: string; module: string; process?: string; kind?: string }> = catalogueRaw.topics ?? catalogueRaw;

const count = <T,>(items: T[], key: (t: T) => string) =>
  items.reduce<Record<string, number>>((acc, t) => {
    const k = key(t);
    acc[k] = (acc[k] ?? 0) + 1;
    return acc;
  }, {});

const dispositionClass = (d?: string) => {
  const v = (d ?? 'content').toLowerCase();
  const classes: [string, string][] = [
    ['index', 'index'], ['blank', 'blank'], ['contributor', 'contributor list'], ['bibliograph', 'bibliography'], ['references', 'references'],
    ['navigation', 'navigation'], ['cover', 'cover'], ['title page', 'title page'], ['copyright', 'copyright'], ['legal', 'legal notice'], ['part divider', 'part divider'],
  ];
  for (const [k, label] of classes) if (v.includes(k)) return label;
  return v === 'content' ? 'content' : 'other';
};

const expected = Number(manifest.totalPdfPages ?? pages.length);
const numbers = new Set(pages.map((p) => p.pdfPage));
const missing: number[] = [];
for (let n = 1; n <= expected; n++) if (!numbers.has(n)) missing.push(n);

const unresolved = pages
  .filter((p) => p.verificationStatus !== 'Verified complete' || (p.issues && p.issues.length > 0) || p.visualInspection === 'Required')
  .map((p) => ({ pdfPage: p.pdfPage, status: p.verificationStatus ?? 'unknown', issues: p.issues ?? [], visual: p.visualInspection ?? '' }));

const contentPages = pages.filter((p) => dispositionClass(p.disposition) === 'content');
const contentWithoutTopics = contentPages.filter((p) => !p.topics || p.topics.length === 0).map((p) => p.pdfPage);

const stats = {
  generatedFrom: ['page-processing-manifest.json', 'source-index.json', 'checkpoint.json', 'topic-catalogue.json'],
  source: manifest.source ?? null,
  expectedPages: expected,
  manifestRecords: pages.length,
  missingPages: missing,
  byBook: count(pages, (p) => p.book),
  byPageType: count(pages, (p) => p.pageType),
  byDisposition: count(pages, (p) => dispositionClass(p.disposition)),
  extraction: count(pages, (p) => p.extractionStatus ?? 'unknown'),
  analysis: count(pages, (p) => p.analysisStatus ?? 'unknown'),
  verification: count(pages, (p) => p.verificationStatus ?? 'unknown'),
  mapping: count(pages, (p) => p.curriculumMapping ?? 'unknown'),
  visualInspection: {
    notRequired: pages.filter((p) => (p.visualInspection ?? '').startsWith('Not required')).length,
    done: pages.filter((p) => (p.visualInspection ?? '').startsWith('Done')).length,
    renderedAndInspected: pages.filter((p) => /render/i.test(p.visualInspection ?? '')).length,
    required: pages.filter((p) => p.visualInspection === 'Required').length,
  },
  pagesWithTopics: pages.filter((p) => p.topics && p.topics.length > 0).length,
  contentPagesWithoutTopics: contentWithoutTopics,
  pagesWithIssues: pages.filter((p) => p.issues && p.issues.length > 0).length,
  unresolved,
  batches: (checkpoint.batches ?? []).length,
  lastVerifiedPdfPage: checkpoint.lastVerifiedPdfPage ?? null,
  index: sourceIndex.counts,
  topics: Object.fromEntries(Object.entries(catalogue).map(([id, t]) => [id, { title: t.title, module: t.module, process: t.process ?? null }])),
};

const out = [
  '/* Generated by scripts/pmp-build-source-stats.ts from docs/pmp-curriculum. Do not edit by hand. */',
  'export interface SourceStats {',
  '  source: string | null; expectedPages: number; manifestRecords: number; missingPages: number[];',
  '  byBook: Record<string, number>; byPageType: Record<string, number>; byDisposition: Record<string, number>;',
  '  extraction: Record<string, number>; analysis: Record<string, number>; verification: Record<string, number>; mapping: Record<string, number>;',
  '  visualInspection: { notRequired: number; done: number; renderedAndInspected: number; required: number };',
  '  pagesWithTopics: number; contentPagesWithoutTopics: number[]; pagesWithIssues: number;',
  '  unresolved: { pdfPage: number; status: string; issues: string[]; visual: string }[];',
  '  batches: number; lastVerifiedPdfPage: number | null; index: Record<string, number>;',
  '  topics: Record<string, { title: string; module: string; process: string | null }>;',
  '  generatedFrom: string[];',
  '}',
  `export const SOURCE_STATS: SourceStats = ${JSON.stringify(stats, null, 1)};`,
  '',
].join('\n');
writeFileSync(new URL('../server/pmp/sourceStats.ts', import.meta.url), out);
console.log(`pages ${stats.manifestRecords}/${stats.expectedPages}, missing ${missing.length}, unresolved ${unresolved.length}, content pages without topics ${contentWithoutTopics.length}`);
